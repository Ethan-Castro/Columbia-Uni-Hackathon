#!/usr/bin/env python3
"""Embed pipeline/hf_release/places.csv into places-data.js so index.html works from disk (file://).
Run from the repo root:  python3 prototypes/before-you-go/build-data.py
Only copies fields the page shows. Nothing is invented or inferred."""
import csv, json, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
src = root / "pipeline" / "hf_release" / "places.csv"
fields = ["id","name","org_type","address","borough","zip","hours","languages","phone","trust","source_url","last_checked"]
rows = [{k: r.get(k, "").strip() for k in fields} for r in csv.DictReader(src.open(encoding="utf-8"))]
out = pathlib.Path(__file__).with_name("places-data.js")
out.write_text("// Generated by build-data.py from pipeline/hf_release/places.csv. Do not edit by hand.\n"
               "window.BYG_DATA = " + json.dumps({"source_file": "pipeline/hf_release/places.csv", "count": len(rows), "places": rows}, ensure_ascii=False) + ";\n",
               encoding="utf-8")
print(f"wrote {out.name}: {len(rows)} places")
